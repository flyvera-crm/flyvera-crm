// Deterministic UUID from a readable key.
const uid = (key) => {
  const h = createHash("md5").update(`flyvera-seed:${key}`).digest("hex");
  return `${h.slice(0, 8)}-${h.slice(8, 12)}-4${h.slice(13, 16)}-${(8 + (parseInt(h[16], 16) & 3)).toString(16)}${h.slice(17, 20)}-${h.slice(20, 32)}`;
};

// ── SQL helpers ───────────────────────────────────────────────────────────────
const raw = (sql) => ({ raw: sql });
const lit = (v) => {
  if (v === null || v === undefined) return "null";
  if (typeof v === "object" && "raw" in v) return v.raw;
  if (typeof v === "number" || typeof v === "boolean") return String(v);
  if (typeof v === "object") return `'${JSON.stringify(v).replace(/'/g, "''")}'::jsonb`;
  return `'${String(v).replace(/'/g, "''")}'`;
};
const out = [];
const sql = (s) => out.push(s);
const insert = (table, cols, rows) => {
  if (!rows.length) return;
  sql(`insert into public.${table} (${cols.join(", ")}) values\n  ${rows.map((r) => `(${r.map(lit).join(", ")})`).join(",\n  ")};\n`);
};
const enc = (n) => raw(`private.encrypt_document(${lit(n)})`);
const splitName = (name) => {
  const [first, ...rest] = name.trim().split(/\s+/);
  return { first, last: rest.join(" ") || first };
};
const money = (n) => Math.round(n * 100) / 100;
const totalOf = (items, discount = 0, taxRate = 0) => {
  const sub = items.reduce((s, i) => s + money(i.quantity * i.unitPrice), 0);
  const taxable = sub - Math.min(discount, sub);
  return money(taxable + money((taxable * taxRate) / 100));
};

